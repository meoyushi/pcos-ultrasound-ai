import { useEffect, useState } from "react";
import { useLocation, useNavigate } from "react-router-dom";

export default function Result() {
  const { state } = useLocation();
  const navigate = useNavigate();

  // Animated confidence bar width
  const [barWidth, setBarWidth] = useState(0);

  useEffect(() => {
    if (!state) return;
    // Trigger bar animation after mount
    const timer = setTimeout(() => setBarWidth(state.confidence || 0), 100);
    return () => clearTimeout(timer);
  }, [state]);

  // Redirect if no result data
  if (!state) {
    navigate("/", { replace: true });
    return null;
  }

  const isPositive = state.prediction === 1;
  const mode = state.mode || "textual";

  return (
    <div className="page fade-in">
      {/* Back button */}
      <button className="back-btn" onClick={() => navigate("/")} type="button">
        <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
          <line x1="19" y1="12" x2="5" y2="12" />
          <polyline points="12 19 5 12 12 5" />
        </svg>
        Back to Home
      </button>

      {/* Result banner */}
      <div className={`result-banner ${isPositive ? "positive" : "negative"}`}>
        <h1 className="result-label">{state.label}</h1>
        <p className="result-subtitle">
          {isPositive
            ? "Our model indicates a likelihood of PCOS. Please consult a healthcare professional."
            : "Our model did not detect significant PCOS indicators."}
        </p>
      </div>

      {/* Stats row */}
      <div className="card" style={{ marginBottom: 24 }}>
        {/* Confidence bar */}
        <div className="confidence-section">
          <div className="confidence-header">
            <h3>Model Confidence</h3>
            <span className="confidence-value">{state.confidence}%</span>
          </div>
          <div className="confidence-bar-bg">
            <div
              className={`confidence-bar-fill ${isPositive ? "high-risk" : ""}`}
              style={{ width: `${barWidth}%` }}
            />
          </div>
        </div>

        {/* PCOS probability */}
        <div className="probability-section">
          <div className={`probability-number ${isPositive ? "positive" : "negative"}`}>
            {state.pcos_probability}%
          </div>
          <p className="probability-label">PCOS Probability</p>
        </div>
      </div>

      {/* Combined breakdown */}
      {mode === "combined" && state.breakdown && (
        <div className="breakdown-section">
          <h3>Prediction Breakdown</h3>
          <div className="breakdown-grid">
            {Object.entries(state.breakdown).map(([key, sub]) => (
              <div className="card breakdown-card" key={key}>
                <h4>{key === "textual" ? "Clinical Data" : "Ultrasound Image"}</h4>
                <div className="breakdown-stat">
                  <span>Result</span>
                  <strong>{sub.label}</strong>
                </div>
                <div className="breakdown-stat">
                  <span>Confidence</span>
                  <strong>{sub.confidence}%</strong>
                </div>
                <div className="breakdown-stat">
                  <span>PCOS Probability</span>
                  <strong>{sub.pcos_probability}%</strong>
                </div>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* Disclaimer */}
      <div className="disclaimer">
        <strong>⚠️ Medical Disclaimer</strong>
        This is not a medical diagnosis. The results are generated by a machine-learning
        model and should not replace professional medical advice. Please consult a
        qualified healthcare professional for proper evaluation and diagnosis.
      </div>

      {/* Action buttons */}
      <div className="result-actions">
        <button className="btn-primary" onClick={() => navigate("/")}>
          Start Over
        </button>
        <button className="btn-secondary" onClick={() => window.print()}>
          Save as PDF
        </button>
      </div>
    </div>
  );
}
